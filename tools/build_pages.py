def esc(value):
    return html.escape(str(value), quote=True)


def tokens(text):
    return int(math.ceil(len(text) / 4.0))


def parse_frontmatter(text):
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None, text
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end = i
            break
    if end is None:
        return None, text
    data = {}
    key = None
    for line in lines[1:end]:
        m = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if m and not line.startswith((" ", "\t")):
            key = m.group(1)
            val = m.group(2).strip()
            if val in (">", "|", ">-", "|-"):
                val = ""
            data[key] = val
        elif key and line.startswith((" ", "\t")):
            data[key] = (data[key] + " " + line.strip()).strip()
    for k in data:
        data[k] = data[k].strip().strip('"').strip("'")
    return data, "\n".join(lines[end + 1:])


def page(title, inner, home, up):
    out = TEMPLATE.replace("__CSS__", CSS)
    out = out.replace("__TITLE__", esc(title))
    out = out.replace("__HOME__", home).replace("__UP__", up)
    return out.replace("__INNER__", inner)


def tally(cases, key):
    got = 0.0
    n = 0
    for c in cases:
        if c.get(key) in POINTS:
            got += POINTS[c[key]]
            n += 1
    if not n:
        return "n/a"
    return ("%d / %d" % (got, n)) if got == int(got) else ("%.1f / %d" % (got, n))


def eval_section(name):
    path = os.path.join(EVALS_DIR, name + ".eval.json")
    if not os.path.exists(path):
        return ('<h2>Evidence</h2><div class="card"><span class="badge none">No eval card yet</span>'
                '<p>This skill has no recorded test results. Add <b>evals/%s.eval.json</b> to show evidence.</p></div>'
                % esc(name))
    try:
        with open(path, encoding="utf-8") as f:
            card = json.load(f)
        cases = card["cases"]
    except (ValueError, KeyError, TypeError):
        return '<h2>Evidence</h2><div class="card"><p>The eval card for this skill could not be read.</p></div>'

    etype = str(card.get("evidence_type", "unknown"))
    label = "Example data" if etype == "example" else etype + " evidence"
    cls = "example" if etype == "example" else "real"
    parts = ['<h2>Evidence</h2><div class="card">']
    parts.append('<span class="badge %s">%s</span>' % (cls, esc(label)))
    parts.append('<div class="meta">Agent: %s &middot; Tested: %s &middot; Version: %s</div>' % (
        esc(card.get("agent", "not stated")), esc(card.get("tested_on", "not stated")),
        esc(card.get("version", "?"))))
    parts.append('<div class="scores"><div class="score"><b>%s</b><span>without the skill</span></div>'
                 '<div class="score"><b>%s</b><span>with the skill</span></div></div>' % (
                     esc(tally(cases, "without_skill")), esc(tally(cases, "with_skill"))))
    for c in cases:
        wo = str(c.get("without_skill", "untested"))
        wi = str(c.get("with_skill", "untested"))
        parts.append('<div class="case"><b>%s</b><div>%s</div>'
                     '<span class="pill %s">without: %s</span><span class="pill %s">with: %s</span></div>' % (
                         esc(c.get("id", "case")), esc(c.get("prompt", "")),
                         esc(wo) if wo in POINTS or wo == "untested" else "untested", esc(wo),
                         esc(wi) if wi in POINTS or wi == "untested" else "untested", esc(wi)))
    parts.append("</div>")
    return "".join(parts)


def build_skill(folder):
    path = os.path.join(SKILLS_DIR, folder, "SKILL.md")
    with open(path, encoding="utf-8") as f:
        text = f.read()
    data, body = parse_frontmatter(text)
    if not data or not data.get("name"):
        print("skip (no valid frontmatter): %s" % path)
        return None
    name = data["name"]
    desc = data.get("description", "")
    always = tokens(name + " " + desc)
    full = tokens(text)

    inner = []
    inner.append("<h1>%s</h1>" % esc(name))
    inner.append('<p class="sub">%s</p>' % esc(desc))
    inner.append('<div class="card"><b>Context cost (estimate)</b>'
                 '<div class="meta">About %d tokens always loaded (name + description), about %d tokens in full. '
                 'Estimates use ~4 characters per token.</div></div>' % (always, full))
    inner.append("<h2>How to <em>install</em></h2>")
    inner.append('<ol class="steps">'
                 '<li>Download the skill folder <b>%s</b> from <a href="%s/tree/main/skills-examples/%s">the repository</a>.</li>'
                 '<li>Place the folder where your agent looks for skills. The location differs by agent, '
                 'so check your agent\'s documentation.</li>'
                 '<li>Ask your agent something that matches the description and see if it uses the skill.</li>'
                 '</ol>' % (esc(folder), REPO, esc(folder)))
    inner.append(eval_section(name))
    inner.append("<h2>Skill <em>text</em></h2>")
    inner.append("<pre>%s</pre>" % esc(text))
    inner.append('<p class="foot">This page was generated from SKILL.md and the eval card. '
                 'Token counts are estimates.</p>')

    target = os.path.join(OUT_DIR, folder)
    os.makedirs(target, exist_ok=True)
    with open(os.path.join(target, "index.html"), "w", encoding="utf-8") as f:
        f.write(page("%s | SkillProof" % name, "".join(inner), "../../", "../"))
    return {"folder": folder, "name": name, "desc": desc, "tokens": full}


def main():
    if not os.path.isdir(SKILLS_DIR):
        print("ERROR: skills-examples/ not found")
        sys.exit(1)
    if os.path.isdir(OUT_DIR):
        shutil.rmtree(OUT_DIR)
    os.makedirs(OUT_DIR)

    built = []
    for folder in sorted(os.listdir(SKILLS_DIR)):
        if os.path.isfile(os.path.join(SKILLS_DIR, folder, "SKILL.md")):
            info = build_skill(folder)
            if info:
                built.append(info)
    if not built:
        print("ERROR: no skills built")
        sys.exit(1)

    inner = ['<h1>Skill <em>Pages</em></h1>',
             '<p class="sub">%d skill(s). Each page shows what the skill does, its context cost, '
             'install steps and evidence.</p>' % len(built)]
    for s in built:
        inner.append('<a class="card" href="%s/"><h3>%s</h3><p>%s</p>'
                     '<div class="meta">~%d tokens in full</div><span class="go">Open &rarr;</span></a>' % (
                         esc(s["folder"]), esc(s["name"]), esc(s["desc"]), s["tokens"]))
    with open(os.path.join(OUT_DIR, "index.html"), "w", encoding="utf-8") as f:
        f.write(page("Skill Pages | SkillProof", "".join(inner), "../", "../"))

    print("Built %d skill page(s): %s" % (len(built), ", ".join(s["name"] for s in built)))


if __name__ == "__main__":
    main()
